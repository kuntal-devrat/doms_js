/// JIT helper for `typeof` operator.
pub extern "C" fn jit_typeof(val: u64) -> u64 {
    CURRENT_VM.with(|c| {
        let vm_ptr = c.get();
        if !vm_ptr.is_null() {
            let vm = unsafe { &mut *vm_ptr };
            let v = JsValue(val);
            let t = if v.is_symbol() {
                "symbol"
            } else if let Some(ptr) = v.as_heap_ptr() {
                let obj = unsafe { &*(ptr as *mut crate::object::JsObject) };
                match &obj.kind {
                    crate::object::ObjectKind::String(_) => "string",
                    crate::object::ObjectKind::Symbol(_) => {
                        if v.is_symbol() {
                            "symbol"
                        } else {
                            "object"
                        }
                    }
                    crate::object::ObjectKind::BigInt(_) => "bigint",
                    crate::object::ObjectKind::Function(_) | crate::object::ObjectKind::NativeFunction(_) => "function",
                    crate::object::ObjectKind::Proxy { target, .. } => {
                        let tgt = *target;
                        if vm.is_callable(tgt) { "function" } else { "object" }
                    }
                    _ => "object",
                }
            } else {
                v.js_typeof()
            };
            let s_val = vm.alloc_string(t.to_string());
            return s_val.0;
        }
        JIT_DEOPT_SENTINEL
    })
}

/// JIT helper for `in` operator (`lhs in rhs`).
pub extern "C" fn jit_in(lhs: u64, rhs: u64) -> u64 {
    CURRENT_VM.with(|c| {
        let vm_ptr = c.get();
        if !vm_ptr.is_null() {
            let vm = unsafe { &mut *vm_ptr };
            let r_val = JsValue(rhs);
            let l_val = JsValue(lhs);
            if !r_val.is_js_object() {
                return JIT_DEOPT_SENTINEL;
            }
            if let Ok(prop_key) = vm.to_property_key(l_val) {
                if let Ok(has) = vm.has_property_key(r_val, &prop_key) {
                    return TAG_BOOLEAN | (has as u64);
                }
            }
        }
        JIT_DEOPT_SENTINEL
    })
}

/// JIT helper for `instanceof` operator (`lhs instanceof rhs`).
pub extern "C" fn jit_instanceof(lhs: u64, rhs: u64) -> u64 {
    CURRENT_VM.with(|c| {
        let vm_ptr = c.get();
        if !vm_ptr.is_null() {
            let vm = unsafe { &mut *vm_ptr };
            let r_val = JsValue(rhs);
            let l_val = JsValue(lhs);
            if !r_val.is_js_object() {
                return JIT_DEOPT_SENTINEL;
            }
            if let Some(has_instance_sym) = vm.symbol_has_instance {
                if let Ok(handler) = vm.get_symbol_property_result(r_val, has_instance_sym) {
                    if !handler.is_undefined() && !handler.is_null() {
                        if !vm.is_callable(handler) {
                            return JIT_DEOPT_SENTINEL;
                        }
                        if let Ok(res) = vm.call(handler, r_val, &[l_val]) {
                            return TAG_BOOLEAN | (res.is_truthy() as u64);
                        }
                        return JIT_DEOPT_SENTINEL;
                    }
                }
            }
            if !vm.is_callable(r_val) {
                return JIT_DEOPT_SENTINEL;
            }
            if let Ok(is_inst) = vm.ordinary_has_instance(r_val, l_val) {
                return TAG_BOOLEAN | (is_inst as u64);
            }
        }
        JIT_DEOPT_SENTINEL
    })
}

/// JIT helper for allocating / interning constant strings of arbitrary length.
pub extern "C" fn jit_alloc_string(ptr: *const u8, len: usize) -> u64 {
    CURRENT_VM.with(|c| {
        let vm_ptr = c.get();
        if !vm_ptr.is_null() && !ptr.is_null() {
            let vm = unsafe { &mut *vm_ptr };
            let slice = unsafe { std::slice::from_raw_parts(ptr, len) };
            if let Ok(s) = std::str::from_utf8(slice) {
                let s_val = vm.alloc_string(s.to_string());
                return s_val.0;
            }
        }
        JIT_DEOPT_SENTINEL
    })
}

/// JIT helper for starting a generator and returning a suspended generator instance.
pub extern "C" fn jit_generator_start(
    resume_ip: u32,
    locals_ptr: *const u64,
    num_locals: u32,
    this_val: u64,
) -> u64 {
    let vm_ptr = CURRENT_VM.with(|c| c.get());
    if vm_ptr.is_null() {
        return TAG_UNDEFINED;
    }
    let vm = unsafe { &mut *vm_ptr };
    let func = match CURRENT_CALLEE_FUNC.with(|c| c.borrow().clone()) {
        Some(f) => f,
        None => return JIT_DEOPT_SENTINEL,
    };

    let locals = if !locals_ptr.is_null() && num_locals > 0 {
        let slice = unsafe { std::slice::from_raw_parts(locals_ptr, num_locals as usize) };
        slice.iter().map(|&bits| JsValue(bits)).collect()
    } else {
        Vec::new()
    };

    let generator_instance = crate::object::JsGenerator {
        function: func,
        ip: resume_ip as usize,
        stack: Vec::new(),
        locals,
        scopes: Vec::new(),
        env_obj: None,
        catch_handlers: Vec::new(),
        state: crate::object::GeneratorState::SuspendedStart,
        this_val: JsValue(this_val),
        arguments: None,
        mapped_arguments: None,
        async_queue: Vec::new(),
    };
    let gen_val = vm.alloc_generator(generator_instance);
    gen_val.0
}

/// JIT helper for suspending a generator frame and constructing `{ value, done: false }`.
pub extern "C" fn jit_generator_suspend(
    yielded_val: u64,
    resume_ip: u32,
    locals_ptr: *const u64,
    num_locals: u32,
) -> u64 {
    let vm_ptr = CURRENT_VM.with(|c| c.get());
    if vm_ptr.is_null() {
        return yielded_val;
    }
    let vm = unsafe { &mut *vm_ptr };
    let gen_raw = CURRENT_GENERATOR.with(|c| c.get());
    if gen_raw != 0 {
        let gen_val = JsValue(gen_raw);
        if let Some(ptr) = gen_val.as_object_ptr() {
            let obj = unsafe { &mut *(ptr as *mut crate::object::JsObject) };
            if let crate::object::ObjectKind::Generator(ref mut g) = obj.kind {
                g.ip = resume_ip as usize;
                g.state = crate::object::GeneratorState::SuspendedYield;
                if !locals_ptr.is_null() && num_locals > 0 {
                    let slice = unsafe { std::slice::from_raw_parts(locals_ptr, num_locals as usize) };
                    g.locals = slice.iter().map(|&bits| JsValue(bits)).collect();
                }
            }
        }
    }
    vm.make_iter_result(JsValue(yielded_val), false).0
}

/// JIT helper for completing a generator and constructing `{ value, done: true }`.
pub extern "C" fn jit_generator_complete(return_val: u64) -> u64 {
    let vm_ptr = CURRENT_VM.with(|c| c.get());
    if vm_ptr.is_null() {
        return return_val;
    }
    let vm = unsafe { &mut *vm_ptr };
    let gen_raw = CURRENT_GENERATOR.with(|c| c.get());
    if gen_raw != 0 {
        let gen_val = JsValue(gen_raw);
        if let Some(ptr) = gen_val.as_object_ptr() {
            let obj = unsafe { &mut *(ptr as *mut crate::object::JsObject) };
            if let crate::object::ObjectKind::Generator(ref mut g) = obj.kind {
                g.state = crate::object::GeneratorState::Completed;
            }
        }
    }
    vm.make_iter_result(JsValue(return_val), true).0
}

