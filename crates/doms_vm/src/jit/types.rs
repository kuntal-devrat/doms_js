//! JIT compilation types, function pointer signatures, and runtime helper functions.

use crate::interpreter::{Vm, VmError};
use crate::value::{JsValue, TAG_BOOLEAN, TAG_UNDEFINED};
use cranelift_jit::JITModule;
use std::sync::Arc;

/// Invocation / loop threshold to trigger JIT compilation.
pub const JIT_HOT_THRESHOLD: u32 = 2;

/// Loop iteration threshold to trigger On-Stack Replacement (OSR).
pub const OSR_HOT_THRESHOLD: u32 = 16;

/// Sentinel NaN-boxed bit pattern indicating speculative check failure (deoptimization).
pub const JIT_DEOPT_SENTINEL: u64 = 0xFFFC_0000_0000_0003;

#[repr(C)]
pub struct NurseryPointers {
    pub bump: *mut u8,
    pub limit: *mut u8,
}

thread_local! {
    pub static NURSERY_PTRS: std::cell::UnsafeCell<NurseryPointers> = const {
        std::cell::UnsafeCell::new(NurseryPointers {
            bump: std::ptr::null_mut(),
            limit: std::ptr::null_mut(),
        })
    };
    pub static CURRENT_VM: std::cell::Cell<*mut Vm> = const {
        std::cell::Cell::new(std::ptr::null_mut())
    };
    pub static CURRENT_GENERATOR: std::cell::Cell<u64> = const {
        std::cell::Cell::new(0)
    };
    pub static CURRENT_GENERATOR_SEND_VAL: std::cell::Cell<u64> = const {
        std::cell::Cell::new(0)
    };
    pub static CURRENT_CALLEE_FUNC: std::cell::RefCell<Option<crate::object::JsFunction>> = const {
        std::cell::RefCell::new(None)
    };
}

pub const JS_OBJECT_SIZE: usize = std::mem::size_of::<crate::object::JsObject>();
pub const TOTAL_ALLOC_SIZE: usize = (doms_gc::header::HEADER_SIZE + JS_OBJECT_SIZE + 7) & !7;

/// Type feedback collected at call and property access sites.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum SpeculativeType {
    Unknown,
    Integer,
    Double,
    Boolean,
    String,
    Object,
}

/// Native machine code function pointer generated by Cranelift JIT.
///
/// Signature: `extern "C" fn(args_ptr: *const u64, num_args: usize, this_val: u64, resume_ip: u64) -> u64`
/// Returns the raw 64-bit NaN-boxed `JsValue.0`.
pub type NativeJitFn = unsafe extern "C" fn(*const u64, usize, u64, u64) -> u64;

/// JIT-compiled native executable block representation.
pub type JitCallable =
    Arc<dyn Fn(&mut Vm, JsValue, &[JsValue]) -> Result<JsValue, VmError> + Send + Sync>;

/// JIT-compiled executable representation.
#[derive(Clone)]
pub enum JitCode {
    /// True native machine code generated by Cranelift JIT
    Native { func_ptr: NativeJitFn, num_locals: usize, _module: Arc<std::sync::Mutex<JITModule>> },
    /// Fast-path interpreted fallback with inlined frame setup
    Interpreted(JitCallable),
}

/// Compiled JIT method containing metadata and compiled function.
#[derive(Clone)]
pub struct JitFunction {
    pub name: Option<String>,
    pub hotness: u32,
    pub specialized_type: SpeculativeType,
    pub code: JitCode,
    pub executable: JitCallable,
}

impl std::fmt::Debug for JitFunction {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("JitFunction")
            .field("name", &self.name)
            .field("hotness", &self.hotness)
            .field("specialized_type", &self.specialized_type)
            .finish()
    }
}

impl JitFunction {
    /// Execute this JIT-compiled function.
    #[inline]
    pub fn call(
        &self,
        vm: &mut Vm,
        this_val: JsValue,
        args: &[JsValue],
    ) -> Result<JsValue, VmError> {
        match &self.code {
            JitCode::Native { func_ptr, num_locals, .. } => {
                let prev_vm = CURRENT_VM.with(|c| c.get());
                CURRENT_VM.with(|c| c.set(vm as *mut Vm));
                NURSERY_PTRS.with(|cell| {
                    let ptrs = unsafe { &mut *cell.get() };
                    ptrs.bump = vm.heap.nursery.cursor();
                    ptrs.limit = vm.heap.nursery.limit();
                });

                let mut raw_args: Vec<u64> = args.iter().map(|v| v.0).collect();
                if raw_args.len() < *num_locals {
                    raw_args.resize(*num_locals, TAG_UNDEFINED);
                }
                let res = unsafe { (func_ptr)(raw_args.as_ptr(), raw_args.len(), this_val.0, 0) };

                NURSERY_PTRS.with(|cell| {
                    let ptrs = unsafe { &mut *cell.get() };
                    if !ptrs.bump.is_null() {
                        if ptrs.bump > vm.heap.nursery.cursor() {
                            vm.heap.nursery.set_cursor(ptrs.bump);
                        } else {
                            ptrs.bump = vm.heap.nursery.cursor();
                        }
                    }
                });
                CURRENT_VM.with(|c| c.set(prev_vm));

                if res == JIT_DEOPT_SENTINEL {
                    return (self.executable)(vm, this_val, args);
                }
                Ok(JsValue(res))
            }
            JitCode::Interpreted(callable) => callable(vm, this_val, args),
        }
    }

    /// Check if this function was compiled into native machine code by Cranelift.
    #[inline]
    pub fn is_native(&self) -> bool {
        matches!(self.code, JitCode::Native { .. })
    }
}

/// Spec-compliant strict equality (`===`) helper for JIT-compiled code.
pub extern "C" fn jit_strict_eq(a: u64, b: u64) -> u64 {
    let eq = crate::object::js_strict_equal(JsValue(a), JsValue(b));
    TAG_BOOLEAN | (eq as u64)
}

/// Spec-compliant strict inequality (`!==`) helper for JIT-compiled code.
pub extern "C" fn jit_strict_neq(a: u64, b: u64) -> u64 {
    let eq = crate::object::js_strict_equal(JsValue(a), JsValue(b));
    TAG_BOOLEAN | ((!eq) as u64)
}

/// Monomorphic property get helper with shape guard.
pub extern "C" fn jit_get_prop_monomorphic(obj: u64, expected_shape: u32, offset: u32) -> u64 {
    let val = JsValue(obj);
    if let Some(ptr) = val.as_object_ptr() {
        let jsobj = unsafe { &*(ptr as *const crate::object::JsObject) };
        if jsobj.shape_id == expected_shape {
            if let Some(v) = jsobj.get_slot(offset) {
                return v.0;
            }
        }
    }
    JIT_DEOPT_SENTINEL
}

/// Monomorphic property set helper with shape guard.
pub extern "C" fn jit_set_prop_monomorphic(
    obj: u64,
    val: u64,
    expected_shape: u32,
    offset: u32,
) -> u64 {
    let target = JsValue(obj);
    if let Some(ptr) = target.as_object_ptr() {
        let jsobj = unsafe { &mut *(ptr as *mut crate::object::JsObject) };
        if jsobj.shape_id == expected_shape {
            jsobj.set_slot(offset, JsValue(val));
            return val;
        }
    }
    JIT_DEOPT_SENTINEL
}

/// Fast array element get helper for dense arrays in JIT code.
#[derive(Clone, Copy)]
pub struct CallCacheEntry {
    pub callee: u64,
    pub func_fn: NativeJitFn,
    pub locals_count: usize,
    pub self_slot: Option<u16>,
}

thread_local! {
    pub static CALL_CACHE: std::cell::Cell<Option<CallCacheEntry>> = const { std::cell::Cell::new(None) };
}

pub fn clear_jit_call_cache() {
    CALL_CACHE.with(|c| c.set(None));
}

#[derive(Clone, Copy)]
pub struct ArrayCacheEntry {
    pub obj_val: u64,
    pub elements_ptr: *const JsValue,
    pub len: usize,
}

thread_local! {
    pub static ARRAY_CACHE: std::cell::Cell<Option<ArrayCacheEntry>> = const { std::cell::Cell::new(None) };
}

pub fn clear_jit_array_cache() {
    ARRAY_CACHE.with(|c| c.set(None));
}

/// Array element get helper for JIT code.
pub extern "C" fn jit_get_elem(obj: u64, key: u64) -> u64 {
    let o = JsValue(obj);
    let k = JsValue(key);
    let idx = if k.is_int32() {
        k.as_int32().unwrap()
    } else {
        match k.to_int32() {
            Some(i) => i,
            None => return JIT_DEOPT_SENTINEL,
        }
    };
    if idx >= 0 {
        if let Some(ptr) = o.as_object_ptr() {
            let jsobj = unsafe { &*(ptr as *const crate::object::JsObject) };
            if !jsobj.has_element_attributes() {
                if let crate::object::ObjectKind::Array(elements) = &jsobj.kind {
                    let uidx = idx as usize;
                    if uidx < elements.len() {
                        let el = elements[uidx];
                        if !el.is_hole() {
                            return el.0;
                        }
                    }
                } else if let crate::object::ObjectKind::TypedArray(ta) = &jsobj.kind {
                    let uidx = idx as usize;
                    if let Some(v) = crate::Vm::read_typed_array_element(ta, uidx) {
                        return v.0;
                    }
                }
            }
        }
    }
    JIT_DEOPT_SENTINEL
}

/// Fast direct dense array element get helper for JIT code.
#[inline(always)]
pub extern "C" fn jit_get_elem_dense(raw_obj: u64, idx_i32: i32) -> u64 {
    if idx_i32 < 0 {
        return JIT_DEOPT_SENTINEL;
    }
    let uidx = idx_i32 as usize;
    if let Some(cache) = ARRAY_CACHE.with(|c| c.get()) {
        if cache.obj_val == raw_obj && uidx < cache.len {
            let el = unsafe { *cache.elements_ptr.add(uidx) };
            if !el.is_hole() {
                return el.0;
            }
        }
    }
    let o = JsValue(raw_obj);
    if let Some(ptr) = o.as_object_ptr() {
        let jsobj = unsafe { &*(ptr as *const crate::object::JsObject) };
        if !jsobj.has_element_attributes() {
            if let crate::object::ObjectKind::Array(elements) = &jsobj.kind {
                let slice = elements.as_slice();
                ARRAY_CACHE.with(|c| {
                    c.set(Some(ArrayCacheEntry {
                        obj_val: raw_obj,
                        elements_ptr: slice.as_ptr(),
                        len: slice.len(),
                    }));
                });
                if uidx < slice.len() {
                    let el = unsafe { *slice.get_unchecked(uidx) };
                    if !el.is_hole() {
                        return el.0;
                    }
                }
            } else if let crate::object::ObjectKind::TypedArray(ta) = &jsobj.kind {
                if let Some(v) = crate::Vm::read_typed_array_element(ta, uidx) {
                    return v.0;
                }
            }
        }
    }
    JIT_DEOPT_SENTINEL
}

/// Array element set helper for JIT code.
pub extern "C" fn jit_set_elem(obj: u64, key: u64, val: u64) -> u64 {
    let o = JsValue(obj);
    let k = JsValue(key);
    let v = JsValue(val);
    let idx = if k.is_int32() {
        k.as_int32().unwrap()
    } else {
        match k.to_int32() {
            Some(i) => i,
            None => return JIT_DEOPT_SENTINEL,
        }
    };
    if idx >= 0 {
        if let Some(ptr) = o.as_object_ptr() {
            let jsobj = unsafe { &mut *(ptr as *mut crate::object::JsObject) };
            if !jsobj.has_element_attributes() {
                if let crate::object::ObjectKind::Array(elements) = &mut jsobj.kind {
                    let uidx = idx as usize;
                    if uidx < elements.len() {
                        elements[uidx] = v;
                        return val;
                    } else if uidx == elements.len() {
                        elements.push(v);
                        return val;
                    }
                } else if let crate::object::ObjectKind::TypedArray(ta) = &mut jsobj.kind {
                    let uidx = idx as usize;
                    if crate::Vm::write_typed_array_element(ta, uidx, v) {
                        return val;
                    }
                }
            }
        }
    }
    JIT_DEOPT_SENTINEL
}

/// Fast direct dense array element set helper for JIT code.
#[inline(always)]
pub extern "C" fn jit_set_elem_dense(raw_obj: u64, idx_i32: i32, val: u64) -> u64 {
    if idx_i32 < 0 {
        return JIT_DEOPT_SENTINEL;
    }
    let uidx = idx_i32 as usize;
    let v = JsValue(val);
    let o = JsValue(raw_obj);
    if let Some(ptr) = o.as_object_ptr() {
        let jsobj = unsafe { &mut *(ptr as *mut crate::object::JsObject) };
        if !jsobj.has_element_attributes() {
            if let crate::object::ObjectKind::Array(elements) = &mut jsobj.kind {
                if uidx < elements.len() {
                    elements[uidx] = v;
                    return val;
                } else if uidx == elements.len() {
                    elements.push(v);
                    let new_slice = elements.as_slice();
                    ARRAY_CACHE.with(|c| {
                        c.set(Some(ArrayCacheEntry {
                            obj_val: raw_obj,
                            elements_ptr: new_slice.as_ptr(),
                            len: new_slice.len(),
                        }));
                    });
                    return val;
                }
            } else if let crate::object::ObjectKind::TypedArray(ta) = &mut jsobj.kind {
                let uidx = idx_i32 as usize;
                if crate::Vm::write_typed_array_element(ta, uidx, v) {
                    return val;
                }
            }
        }
    }
    JIT_DEOPT_SENTINEL
}

/// Array allocation helper for JIT code.
pub extern "C" fn jit_alloc_array(count: usize) -> u64 {
    CURRENT_VM.with(|c| {
        let vm_ptr = c.get();
        if !vm_ptr.is_null() {
            let vm = unsafe { &mut *vm_ptr };
            let arr = vm.alloc_array(Vec::with_capacity(count));
            arr.0
        } else {
            JIT_DEOPT_SENTINEL
        }
    })
}

/// Array allocation with initial elements helper for JIT code.
pub extern "C" fn jit_alloc_array_with_elements(elements_ptr: *const u64, count: usize) -> u64 {
    CURRENT_VM.with(|c| {
        let vm_ptr = c.get();
        if !vm_ptr.is_null() {
            let vm = unsafe { &mut *vm_ptr };
            let mut elements = Vec::with_capacity(count);
            if count > 0 && !elements_ptr.is_null() {
                let slice = unsafe { std::slice::from_raw_parts(elements_ptr, count) };
                for &v in slice {
                    elements.push(JsValue(v));
                }
            }
            let arr = vm.alloc_array(elements);
            arr.0
        } else {
            JIT_DEOPT_SENTINEL
        }
    })
}

/// Object allocation helper for JIT code.
pub extern "C" fn jit_alloc_object() -> u64 {
    CURRENT_VM.with(|c| {
        let vm_ptr = c.get();
        if !vm_ptr.is_null() {
            let vm = unsafe { &mut *vm_ptr };
            let obj = vm.alloc_object();
            obj.0
        } else {
            JIT_DEOPT_SENTINEL
        }
    })
}

/// Spec-compliant modulo helper for JIT-compiled code.
pub extern "C" fn jit_mod(a: u64, b: u64) -> u64 {
    let va = JsValue(a);
    let vb = JsValue(b);
    let na = if let Some(n) = va.as_number() {
        n
    } else {
        return JIT_DEOPT_SENTINEL;
    };
    let nb = if let Some(n) = vb.as_number() {
        n
    } else {
        return JIT_DEOPT_SENTINEL;
    };
    JsValue::from_double(na % nb).0
}

pub const TAG_ARRAY_PUSH_FN: u64 = 0xFFFA_0000_0000_0001;

/// Fast array length helper for JIT code.
#[inline(always)]
pub extern "C" fn jit_array_length(obj: u64) -> u64 {
    let o = JsValue(obj);
    if let Some(ptr) = o.as_object_ptr() {
        let jsobj = unsafe { &*(ptr as *const crate::object::JsObject) };
        if !jsobj.has_element_attributes() {
            if let crate::object::ObjectKind::Array(elements) = &jsobj.kind {
                let len = elements.len();
                ARRAY_CACHE.with(|c| {
                    c.set(Some(ArrayCacheEntry {
                        obj_val: obj,
                        elements_ptr: elements.as_ptr(),
                        len,
                    }));
                });
                if len <= (i32::MAX as usize) {
                    return crate::value::TAG_INT32 | (len as u32 as u64);
                } else {
                    return JsValue::from_double(len as f64).0;
                }
            }
        }
    }
    JIT_DEOPT_SENTINEL
}

/// Fast inlined array push helper for JIT code.
#[inline(always)]
pub extern "C" fn jit_array_push_fast(obj: u64, val: u64) -> u64 {
    let o = JsValue(obj);
    if let Some(ptr) = o.as_object_ptr() {
        let jsobj = unsafe { &mut *(ptr as *mut crate::object::JsObject) };
        if !jsobj.has_element_attributes() && jsobj.is_extensible() {
            if let crate::object::ObjectKind::Array(elements) = &mut jsobj.kind {
                let len = elements.len();
                let cap = elements.capacity();
                let v = JsValue(val);
                if len < cap {
                    unsafe {
                        let end_ptr = elements.as_mut_ptr().add(len);
                        std::ptr::write(end_ptr, v);
                        elements.set_len(len + 1);
                    }
                } else {
                    elements.push(v);
                }
                let new_len = len + 1;
                let new_ptr = elements.as_ptr();
                ARRAY_CACHE.with(|c| {
                    c.set(Some(ArrayCacheEntry {
                        obj_val: obj,
                        elements_ptr: new_ptr,
                        len: new_len,
                    }));
                });
                if new_len <= (i32::MAX as usize) {
                    return crate::value::TAG_INT32 | (new_len as u32 as u64);
                } else {
                    return JsValue::from_double(new_len as f64).0;
                }
            }
        }
    }
    JIT_DEOPT_SENTINEL
}

/// Native C-ABI call trampoline for JIT-to-JIT calls.
pub extern "C" fn jit_call_trampoline(
    callee: u64,
    _this_val: u64,
    args_ptr: *const u64,
    argc: usize,
) -> u64 {
    if callee == TAG_ARRAY_PUSH_FN {
        if argc > 0 && !args_ptr.is_null() {
            let mut last_res = _this_val;
            for i in 0..argc {
                let arg = unsafe { *args_ptr.add(i) };
                last_res = jit_array_push_fast(_this_val, arg);
            }
            return last_res;
        }
    }

    if let Some(entry) = CALL_CACHE.with(|c| c.get()) {
        if entry.callee == callee {
            if entry.locals_count <= 16 {
                let mut fast_args = [TAG_UNDEFINED; 16];
                let to_copy = argc.min(entry.locals_count);
                if to_copy > 0 && !args_ptr.is_null() {
                    let raw_slice = unsafe { std::slice::from_raw_parts(args_ptr, to_copy) };
                    fast_args[..to_copy].copy_from_slice(raw_slice);
                }
                if let Some(slot) = entry.self_slot {
                    if (slot as usize) < entry.locals_count {
                        fast_args[slot as usize] = callee;
                    }
                }
                let res = unsafe {
                    (entry.func_fn)(fast_args.as_mut_ptr(), entry.locals_count, _this_val, 0)
                };
                if res != JIT_DEOPT_SENTINEL {
                    return res;
                }
            }
        }
    }

    let callee_val = JsValue(callee);
    if let Some(ptr) = callee_val.as_object_ptr() {
        let obj = unsafe { &mut *(ptr as *mut crate::object::JsObject) };
        if let crate::object::ObjectKind::NativeFunction(ref nf) = obj.kind {
            if nf.name == "push" && argc > 0 && !args_ptr.is_null() {
                let mut last_res = _this_val;
                for i in 0..argc {
                    let arg = unsafe { *args_ptr.add(i) };
                    last_res = jit_array_push_fast(_this_val, arg);
                }
                return last_res;
            }
        }
        if let crate::object::ObjectKind::Function(ref mut f) = obj.kind {
            if f.jit_entry.is_none() && !f.jit_attempted {
                f.jit_attempted = true;
                f.jit_entry = crate::jit::JitCompiler::compile_native(&f.chunk);
            }
            if let Some(jit) = &f.jit_entry {
                if let JitCode::Native { func_ptr, num_locals, .. } = &jit.code {
                    let locals_count = *num_locals;
                    let self_slot = f.self_slot;
                    let func_fn = *func_ptr;

                    CALL_CACHE.with(|c| {
                        c.set(Some(CallCacheEntry { callee, func_fn, locals_count, self_slot }));
                    });

                    if locals_count <= 16 {
                        let mut fast_args = [TAG_UNDEFINED; 16];
                        let to_copy = argc.min(locals_count);
                        if to_copy > 0 && !args_ptr.is_null() {
                            let raw_slice =
                                unsafe { std::slice::from_raw_parts(args_ptr, to_copy) };
                            fast_args[..to_copy].copy_from_slice(raw_slice);
                        }
                        if let Some(slot) = self_slot {
                            if (slot as usize) < locals_count {
                                fast_args[slot as usize] = callee;
                            }
                        }
                        let res =
                            unsafe { (func_fn)(fast_args.as_mut_ptr(), locals_count, _this_val, 0) };
                        if res != JIT_DEOPT_SENTINEL {
                            return res;
                        }
                    } else {
                        let mut fast_args = Vec::with_capacity(locals_count);
                        if argc > 0 && !args_ptr.is_null() {
                            let raw_slice = unsafe { std::slice::from_raw_parts(args_ptr, argc) };
                            fast_args.extend_from_slice(raw_slice);
                        }
                        if fast_args.len() < locals_count {
                            fast_args.resize(locals_count, TAG_UNDEFINED);
                        }
                        if let Some(slot) = self_slot {
                            if (slot as usize) < fast_args.len() {
                                fast_args[slot as usize] = callee;
                            }
                        }
                        let res = unsafe {
                            (func_fn)(fast_args.as_mut_ptr(), fast_args.len(), _this_val, 0)
                        };
                        if res != JIT_DEOPT_SENTINEL {
                            return res;
                        }
                    }
                }
            }
        }
    }

    let vm_ptr = CURRENT_VM.with(|c| c.get());
    if !vm_ptr.is_null() {
        let vm = unsafe { &mut *vm_ptr };
        NURSERY_PTRS.with(|cell| {
            let ptrs = unsafe { &*cell.get() };
            if !ptrs.bump.is_null() {
                vm.heap.nursery.set_cursor(ptrs.bump);
            }
        });
        let mut stack_args = [JsValue::undefined(); 16];
        let to_copy = argc.min(16);
        if to_copy > 0 && !args_ptr.is_null() {
            let raw_slice = unsafe { std::slice::from_raw_parts(args_ptr, to_copy) };
            for (i, &v) in raw_slice.iter().enumerate() {
                stack_args[i] = JsValue(v);
            }
        }
        let target_depth = vm.frames.len();
        let call_res =
            vm.execute_call_internal(callee_val, JsValue(_this_val), &stack_args[..to_copy]);
        let res = if let Ok(Some(r)) = call_res {
            r
        } else if call_res.is_ok() {
            vm.run_until_depth(target_depth).unwrap_or(JsValue::undefined())
        } else {
            return JIT_DEOPT_SENTINEL;
        };
        NURSERY_PTRS.with(|cell| {
            let ptrs = unsafe { &mut *cell.get() };
            ptrs.bump = vm.heap.nursery.cursor();
            ptrs.limit = vm.heap.nursery.limit();
        });
        return res.0;
    }

    JIT_DEOPT_SENTINEL
}

/// Native C-ABI constructor trampoline for JIT code with nursery bump allocation.
pub extern "C" fn jit_construct_trampoline(callee: u64, args_ptr: *const u64, argc: usize) -> u64 {
    let callee_val = JsValue(callee);
    if let Some(ptr) = callee_val.as_object_ptr() {
        let obj = unsafe { &mut *(ptr as *mut crate::object::JsObject) };
        if let crate::object::ObjectKind::Function(ref mut f) = obj.kind {
            if let Some(shape_id) = f.initial_shape {
                if f.jit_entry.is_none() && !f.jit_attempted {
                    f.jit_attempted = true;
                    f.jit_entry = crate::jit::JitCompiler::compile_native(&f.chunk);
                }
                // Fast bump allocation in young generation nursery
                let alloc_size = TOTAL_ALLOC_SIZE;
                let bump_opt = NURSERY_PTRS.with(|cell| {
                    let ptrs = unsafe { &mut *cell.get() };
                    if !ptrs.bump.is_null() && ptrs.bump < ptrs.limit {
                        let remaining = unsafe { ptrs.limit.offset_from(ptrs.bump) } as usize;
                        if remaining >= alloc_size {
                            let curr = ptrs.bump;
                            ptrs.bump = unsafe { ptrs.bump.add(alloc_size) };
                            return Some(curr);
                        }
                    }
                    None
                });

                let this_obj_ptr = if let Some(bump) = bump_opt {
                    let header_ptr = bump as *mut doms_gc::GcHeader;
                    let payload = unsafe {
                        std::ptr::write(
                            header_ptr,
                            doms_gc::GcHeader::new(
                                alloc_size as u32,
                                doms_gc::header::TypeTag::Object,
                            ),
                        );
                        let p = header_ptr.add(1) as *mut crate::object::JsObject;
                        std::ptr::write(
                            p,
                            crate::object::JsObject::new_ordinary(shape_id, f.prototype),
                        );
                        p
                    };
                    let vm_ptr = CURRENT_VM.with(|c| c.get());
                    if !vm_ptr.is_null() {
                        unsafe {
                            (*vm_ptr).track_ptr(payload);
                        }
                    }
                    payload
                } else {
                    let vm_ptr = CURRENT_VM.with(|c| c.get());
                    if vm_ptr.is_null() {
                        return JIT_DEOPT_SENTINEL;
                    }
                    let vm = unsafe { &mut *vm_ptr };
                    NURSERY_PTRS.with(|cell| {
                        let ptrs = unsafe { &*cell.get() };
                        if !ptrs.bump.is_null() {
                            vm.heap.nursery.set_cursor(ptrs.bump);
                        }
                    });
                    let proto = f.prototype.or(vm.object_proto);
                    let val = vm.alloc_object_with_shape_and_proto(shape_id, proto);
                    NURSERY_PTRS.with(|cell| {
                        let ptrs = unsafe { &mut *cell.get() };
                        ptrs.bump = vm.heap.nursery.cursor();
                        ptrs.limit = vm.heap.nursery.limit();
                    });
                    val.as_object_ptr().unwrap() as *mut crate::object::JsObject
                };

                let this_val = unsafe { JsValue::from_object_ptr(this_obj_ptr as *mut u8) };

                // Call constructor body with native JIT function if available
                if let Some(jit) = &f.jit_entry {
                    if let JitCode::Native { func_ptr, num_locals, .. } = &jit.code {
                        let locals_count = *num_locals;
                        let self_slot = f.self_slot;
                        let func_fn = *func_ptr;

                        if locals_count <= 16 {
                            let mut fast_args = [TAG_UNDEFINED; 16];
                            let to_copy = argc.min(locals_count);
                            if to_copy > 0 && !args_ptr.is_null() {
                                let raw_slice =
                                    unsafe { std::slice::from_raw_parts(args_ptr, to_copy) };
                                fast_args[..to_copy].copy_from_slice(raw_slice);
                            }
                            if let Some(slot) = self_slot {
                                if (slot as usize) < locals_count {
                                    fast_args[slot as usize] = callee;
                                }
                            }
                            let res = unsafe {
                                (func_fn)(fast_args.as_mut_ptr(), locals_count, this_val.0, 0)
                            };
                            if res != JIT_DEOPT_SENTINEL {
                                let res_val = JsValue(res);
                                if res_val.is_object() {
                                    return res;
                                }
                                return this_val.0;
                            }
                        } else {
                            let mut fast_args = Vec::with_capacity(locals_count);
                            if argc > 0 && !args_ptr.is_null() {
                                let raw_slice =
                                    unsafe { std::slice::from_raw_parts(args_ptr, argc) };
                                fast_args.extend_from_slice(raw_slice);
                            }
                            if fast_args.len() < locals_count {
                                fast_args.resize(locals_count, TAG_UNDEFINED);
                            }
                            if let Some(slot) = self_slot {
                                if (slot as usize) < fast_args.len() {
                                    fast_args[slot as usize] = callee;
                                }
                            }
                            let res = unsafe {
                                (func_fn)(fast_args.as_mut_ptr(), fast_args.len(), this_val.0, 0)
                            };
                            if res != JIT_DEOPT_SENTINEL {
                                let res_val = JsValue(res);
                                if res_val.is_object() {
                                    return res;
                                }
                                return this_val.0;
                            }
                        }
                    }
                }

                // If native didn't execute or deopted, run execute_call_internal
                let vm_ptr = CURRENT_VM.with(|c| c.get());
                if !vm_ptr.is_null() {
                    let vm = unsafe { &mut *vm_ptr };
                    NURSERY_PTRS.with(|cell| {
                        let ptrs = unsafe { &*cell.get() };
                        if !ptrs.bump.is_null() {
                            vm.heap.nursery.set_cursor(ptrs.bump);
                        }
                    });
                    let mut stack_args = [JsValue::undefined(); 8];
                    let to_copy = argc.min(8);
                    if to_copy > 0 && !args_ptr.is_null() {
                        let raw_slice = unsafe { std::slice::from_raw_parts(args_ptr, to_copy) };
                        for (i, &v) in raw_slice.iter().enumerate() {
                            stack_args[i] = JsValue(v);
                        }
                    }
                    let prev_constructing = vm.is_constructing;
                    vm.is_constructing = true;
                    let target_depth = vm.frames.len();
                    let call_res =
                        vm.execute_call_internal(callee_val, this_val, &stack_args[..to_copy]);
                    let res = if let Ok(Some(r)) = call_res {
                        r
                    } else if call_res.is_ok() {
                        vm.run_until_depth(target_depth).unwrap_or(this_val)
                    } else {
                        this_val
                    };
                    vm.is_constructing = prev_constructing;
                    NURSERY_PTRS.with(|cell| {
                        let ptrs = unsafe { &mut *cell.get() };
                        ptrs.bump = vm.heap.nursery.cursor();
                        ptrs.limit = vm.heap.nursery.limit();
                    });
                    if res.is_object() {
                        return res.0;
                    }
                    return this_val.0;
                }
                return this_val.0;
            } else {
                // First call: execute VM construct to initialize initial_shape
                let vm_ptr = CURRENT_VM.with(|c| c.get());
                if !vm_ptr.is_null() {
                    let vm = unsafe { &mut *vm_ptr };
                    NURSERY_PTRS.with(|cell| {
                        let ptrs = unsafe { &*cell.get() };
                        if !ptrs.bump.is_null() {
                            vm.heap.nursery.set_cursor(ptrs.bump);
                        }
                    });
                    let mut stack_args = [JsValue::undefined(); 8];
                    let to_copy = argc.min(8);
                    if to_copy > 0 && !args_ptr.is_null() {
                        let raw_slice = unsafe { std::slice::from_raw_parts(args_ptr, to_copy) };
                        for (i, &v) in raw_slice.iter().enumerate() {
                            stack_args[i] = JsValue(v);
                        }
                    }
                    let res = vm.construct(callee_val, &stack_args[..to_copy]);
                    NURSERY_PTRS.with(|cell| {
                        let ptrs = unsafe { &mut *cell.get() };
                        ptrs.bump = vm.heap.nursery.cursor();
                        ptrs.limit = vm.heap.nursery.limit();
                    });
                    if let Ok(res_val) = res {
                        return res_val.0;
                    }
                }
            }
        }
    }
    JIT_DEOPT_SENTINEL
}

/// Global get helper for JIT-compiled code.
pub extern "C" fn jit_get_global(name_ptr: *const u8, name_len: usize) -> u64 {
    CURRENT_VM.with(|c| {
        let vm_ptr = c.get();
        if vm_ptr.is_null() || name_ptr.is_null() {
            return JIT_DEOPT_SENTINEL;
        }
        let vm = unsafe { &mut *vm_ptr };
        let slice = unsafe { std::slice::from_raw_parts(name_ptr, name_len) };
        let name = match std::str::from_utf8(slice) {
            Ok(s) => s,
            Err(_) => return JIT_DEOPT_SENTINEL,
        };
        match vm.resolve_identifier(name) {
            Ok(Some(val)) => {
                if val.is_uninitialized() {
                    JIT_DEOPT_SENTINEL
                } else {
                    val.0
                }
            }
            _ => JIT_DEOPT_SENTINEL,
        }
    })
}

